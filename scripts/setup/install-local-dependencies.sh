#!/usr/bin/env bash
# Install the local EPM finance platform dependencies into the current Kubernetes context.
# Idempotent. All credentials are generated at install time into .secrets/local.env
# (gitignored); committed manifests reference Secrets by name only - no credential
# literals ever enter the repository.
#
# Exposed endpoints (via scripts/setup/create-local-cluster.sh port mappings):
#   APISIX gateway      http://localhost:18080
#   Keycloak            http://localhost:18081
#   OTel collector      http://localhost:18888/metrics
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "${REPO_ROOT}"
SECRETS_DIR="${REPO_ROOT}/.secrets"
SECRETS_ENV="${SECRETS_DIR}/local.env"

command -v kubectl >/dev/null 2>&1 || { echo "FAIL: kubectl is not installed" >&2; exit 1; }
kubectl get --raw /readyz >/dev/null 2>&1 || { echo "FAIL: no healthy cluster in current context" >&2; exit 1; }

echo "[deps] building finance-core image"
./mvnw -q -pl services/finance-core -DskipTests package
docker build -q -f services/finance-core/src/main/docker/Dockerfile.jvm -t finance-core:r0 services/finance-core
echo "[deps] loading image into kind"
kind load docker-image finance-core:r0 --name "${EPM_KIND_CLUSTER:-epm-finance}"

echo "[deps] generating install-time credentials"
mkdir -p "${SECRETS_DIR}"
chmod 700 "${SECRETS_DIR}"
PG_PASSWORD="$(head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 28)"
KC_ADMIN_PASSWORD="$(head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 28)"
SMOKE_PASSWORD="$(head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 28)"
GATEWAY_CLIENT_SECRET="$(head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 32)"
cat > "${SECRETS_ENV}" <<EOF
# Generated by scripts/setup/install-local-dependencies.sh - LOCAL SYNTHETIC ENVIRONMENT ONLY.
EPM_POSTGRES_PASSWORD=${PG_PASSWORD}
EPM_KEYCLOAK_ADMIN_PASSWORD=${KC_ADMIN_PASSWORD}
EPM_SMOKE_PASSWORD=${SMOKE_PASSWORD}
EPM_GATEWAY_CLIENT_SECRET=${GATEWAY_CLIENT_SECRET}
EPM_GATEWAY_URL=http://localhost:18080
EPM_KEYCLOAK_URL=http://localhost:18081
EPM_KEYCLOAK_REALM=epm
EPM_COLLECTOR_METRICS_URL=http://localhost:18888/metrics
EOF
chmod 600 "${SECRETS_ENV}"
if ! grep -qx '.secrets/' .gitignore 2>/dev/null; then
  echo "[deps] FAIL: .secrets/ must be listed in .gitignore before generating credentials" >&2
  exit 1
fi

echo "[deps] creating secrets"
kubectl -n epm-system create namespace epm-system --dry-run=client -o yaml | kubectl apply -f -
kubectl -n epm-system create secret generic postgres-credentials \
  --from-literal=POSTGRES_PASSWORD="${PG_PASSWORD}" \
  --dry-run=client -o yaml | kubectl apply -f -
kubectl -n epm-system create secret generic keycloak-bootstrap \
  --from-literal=KC_BOOTSTRAP_ADMIN_USERNAME=admin \
  --from-literal=KC_BOOTSTRAP_ADMIN_PASSWORD="${KC_ADMIN_PASSWORD}" \
  --from-literal=SMOKE_PASSWORD="${SMOKE_PASSWORD}" \
  --dry-run=client -o yaml | kubectl apply -f -

# Realm import file and APISIX route config are rendered from committed templates,
# substituting install-time generated secrets; rendered files never enter git.
mkdir -p "${SECRETS_DIR}/rendered"
sed -e "s/__SMOKE_PASSWORD__/${SMOKE_PASSWORD}/" \
    -e "s/__GATEWAY_CLIENT_SECRET__/${GATEWAY_CLIENT_SECRET}/" \
  deploy/apisix/realm-template.json > "${SECRETS_DIR}/rendered/realm.json"
kubectl -n epm-system create configmap keycloak-realm \
  --from-file=realm.json="${SECRETS_DIR}/rendered/realm.json" \
  --dry-run=client -o yaml | kubectl apply -f -

# Stage rendered configs where kustomize can read them (inside the base root).
mkdir -p deploy/kubernetes/base/generated
cp deploy/observability/otel-collector.yaml deploy/kubernetes/base/generated/otel-collector.yaml
cp deploy/apisix/apisix-config.yaml deploy/kubernetes/base/generated/apisix-main.yaml
sed "s/__GATEWAY_CLIENT_SECRET__/${GATEWAY_CLIENT_SECRET}/" \
  deploy/apisix/routes.yaml > deploy/kubernetes/base/generated/apisix-routes.yaml

echo "[deps] applying platform manifests"
kubectl -n epm-system delete job postgres-age-init --ignore-not-found=true
kubectl apply -k deploy/kubernetes/overlays/dev

echo "[deps] waiting for rollouts"
kubectl -n epm-system wait --for=condition=available --timeout=300s deployment/apisix
kubectl -n epm-system wait --for=condition=available --timeout=300s deployment/keycloak
kubectl -n epm-system wait --for=condition=available --timeout=300s deployment/otel-collector
kubectl -n epm-system wait --for=condition=available --timeout=300s deployment/finance-core
kubectl -n epm-system rollout status statefulset/postgres-age --timeout=300s

echo "[deps] waiting for PostgreSQL readiness"
kubectl -n epm-system wait --for=condition=Ready pod -l app=postgres-age --timeout=300s

# Record the cluster node address so smoke tests can reach NodePorts that have no host
# port mapping (received-metrics exposition on 30089).
NODE_ADDRESS="$(docker inspect "${EPM_KIND_CLUSTER:-epm-finance}-control-plane" \
  --format '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' 2>/dev/null || echo localhost):30089"
if ! grep -q '^EPM_NODE_ADDRESS=' "${SECRETS_ENV}"; then
  echo "EPM_NODE_ADDRESS=${NODE_ADDRESS}" >> "${SECRETS_ENV}"
else
  sed -i.bak "s|^EPM_NODE_ADDRESS=.*|EPM_NODE_ADDRESS=${NODE_ADDRESS}|" "${SECRETS_ENV}" && rm -f "${SECRETS_ENV}.bak"
fi

echo "PASS: platform installed. Source ${SECRETS_ENV} for smoke-test credentials."
